from qgis.PyQt.QtWidgets import QAction
from qgis.gui import QgsMapToolEmitPoint
from qgis.core import (
    QgsCoordinateTransform,
    QgsCoordinateReferenceSystem,
    QgsProject
)

from .Coordinate_Formatter_dialog import CoordinateFormatterDialog


class CoordinateFormatter:
    def __init__(self, iface):
        self.iface = iface
        self.canvas = iface.mapCanvas()
        self.action = None

        self.map_tool = QgsMapToolEmitPoint(self.canvas)
        self.map_tool.canvasClicked.connect(self.handle_click)

    def initGui(self):
        self.action = QAction("Coordinate Formatter", self.iface.mainWindow())
        self.action.triggered.connect(self.run)
        self.iface.addToolBarIcon(self.action)
        self.iface.addPluginToMenu("&Coordinate Formatter", self.action)

    def unload(self):
        self.iface.removeToolBarIcon(self.action)
        self.iface.removePluginMenu("&Coordinate Formatter", self.action)

    def run(self):
        self.canvas.setMapTool(self.map_tool)

    def handle_click(self, point, button):
        source_crs = self.canvas.mapSettings().destinationCrs()
        wgs84 = QgsCoordinateReferenceSystem("EPSG:4326")

        transform = QgsCoordinateTransform(
            source_crs,
            wgs84,
            QgsProject.instance()
        )

        wgs_point = transform.transform(point)

        dlg = CoordinateFormatterDialog(wgs_point)
        dlg.show()
